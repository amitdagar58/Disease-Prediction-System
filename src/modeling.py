import hashlib
import json
import os
import tempfile
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.impute import SimpleImputer
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.neighbors import KNeighborsClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.naive_bayes import GaussianNB
from sklearn.svm import LinearSVC
from src.config import RANDOM_STATE, TEST_SIZE, MODEL_DIR

MAX_TRAINING_ROWS = 3000  # Small reproducible sample for responsive first-run training
MODEL_FILE = MODEL_DIR / "trained_models.joblib"
METADATA_FILE = MODEL_DIR / "model_metadata.json"
CACHE_FORMAT_VERSION = 1


def _build_preprocessor(X):
    numeric = list(X.select_dtypes(include=["number", "bool"]).columns)
    categorical = [c for c in X.columns if c not in numeric]
    transformers = []
    if numeric:
        transformers.append(("numeric", Pipeline([
            ("imputer", SimpleImputer(strategy="most_frequent")),
            ("scaler", StandardScaler())
        ]), numeric))
    if categorical:
        transformers.append(("categorical", Pipeline([
            ("imputer", SimpleImputer(strategy="most_frequent")),
            ("onehot", OneHotEncoder(handle_unknown="ignore"))
        ]), categorical))
    return ColumnTransformer(transformers=transformers, remainder="drop")


def _models():
    return {
        "Decision Tree": DecisionTreeClassifier(random_state=RANDOM_STATE, class_weight="balanced"),
        "Random Forest": RandomForestClassifier(n_estimators=35, random_state=RANDOM_STATE, class_weight="balanced", n_jobs=-1),
        "KNN": KNeighborsClassifier(n_neighbors=5, n_jobs=-1),
        "Logistic Regression": LogisticRegression(max_iter=150, class_weight="balanced", solver="lbfgs"),
        "Naive Bayes": GaussianNB(),
        "SVM": LinearSVC(class_weight="balanced", random_state=RANDOM_STATE, max_iter=500, dual="auto")
    }


def _limit_rows(df, target_col):
    if len(df) <= MAX_TRAINING_ROWS:
        return df
    y = df[target_col].astype(str)
    counts = y.value_counts()
    if counts.min() >= 2 and y.nunique() < MAX_TRAINING_ROWS:
        try:
            sampled, _ = train_test_split(
                df, train_size=MAX_TRAINING_ROWS, random_state=RANDOM_STATE, stratify=y
            )
            return sampled.reset_index(drop=True)
        except ValueError:
            pass
    return df.sample(n=MAX_TRAINING_ROWS, random_state=RANDOM_STATE).reset_index(drop=True)


def _cache_key(df, target_col, feature_cols):
    """Fingerprint data, selected columns and training configuration."""
    digest = hashlib.sha256()
    digest.update(pd.util.hash_pandas_object(df, index=True).values.tobytes())
    settings = {
        "columns": [str(c) for c in df.columns],
        "target": str(target_col),
        "features": [str(c) for c in feature_cols],
        "random_state": RANDOM_STATE,
        "test_size": TEST_SIZE,
        "max_training_rows": MAX_TRAINING_ROWS,
        "sklearn_version": sklearn.__version__,
        "cache_format_version": CACHE_FORMAT_VERSION,
    }
    digest.update(json.dumps(settings, sort_keys=True).encode("utf-8"))
    return digest.hexdigest(), settings


def _load_saved_models(cache_key):
    """Load only the locally generated cache when its fingerprint matches."""
    if not MODEL_FILE.exists():
        return None
    try:
        # Joblib/pickle files can execute code. Only load files generated by this project.
        artifact = joblib.load(MODEL_FILE)
        if artifact.get("cache_key") != cache_key:
            return None
        required = {"models", "metrics", "feature_cols", "training_info"}
        if not required.issubset(artifact):
            return None
        return (
            artifact["models"], artifact["metrics"],
            artifact["feature_cols"], artifact["training_info"]
        )
    except Exception:
        # A damaged or incompatible cache is safely ignored and rebuilt below.
        return None


def _save_models(cache_key, settings, fitted, metrics, feature_cols, training_info):
    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    artifact = {
        "cache_key": cache_key,
        "models": fitted,
        "metrics": metrics,
        "feature_cols": list(feature_cols),
        "training_info": training_info,
    }
    fd, temp_name = tempfile.mkstemp(prefix="trained_models_", suffix=".tmp", dir=MODEL_DIR)
    os.close(fd)
    temp_path = Path(temp_name)
    try:
        joblib.dump(artifact, temp_path, compress=3)
        temp_path.replace(MODEL_FILE)
    finally:
        if temp_path.exists():
            temp_path.unlink()

    metadata = {
        "cache_key": cache_key,
        "created_at": pd.Timestamp.now(tz="UTC").isoformat(),
        "scikit_learn_version": sklearn.__version__,
        "dataset_rows": int(training_info["full_rows"]),
        "training_rows": int(training_info["training_rows"]),
        "selected_by": "highest macro F1-score on held-out test split",
        "metrics": metrics.to_dict(orient="records"),
        "settings": settings,
    }
    temp_meta = METADATA_FILE.with_suffix(".json.tmp")
    temp_meta.write_text(json.dumps(metadata, indent=2, default=str), encoding="utf-8")
    temp_meta.replace(METADATA_FILE)


def load_or_train_models(df, target_col, feature_cols):
    # Persistent disk cache: subsequent app runs load trained models rather than fitting again.
    cache_key, settings = _cache_key(df, target_col, feature_cols)
    saved = _load_saved_models(cache_key)
    if saved is not None:
        models, metrics, saved_features, training_info = saved
        training_info = dict(training_info)
        training_info["cache_status"] = "loaded"
        return models, metrics, saved_features, training_info

    work_df = _limit_rows(df, target_col)
    X = work_df[list(feature_cols)].copy()
    y = work_df[target_col].astype(str)
    if y.nunique() < 2:
        raise ValueError("The target column must contain at least two different disease labels.")
    counts = y.value_counts()
    can_stratify = counts.min() >= 2
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=TEST_SIZE, random_state=RANDOM_STATE,
        stratify=y if can_stratify else None
    )
    fitted, records = {}, []
    for name, estimator in _models().items():
        pipeline = Pipeline([
            ("preprocess", _build_preprocessor(X_train)),
            ("classifier", estimator)
        ])
        try:
            pipeline.fit(X_train, y_train)
            pred = pipeline.predict(X_test)
            fitted[name] = pipeline
            records.append({
                "Algorithm": name,
                "Accuracy": accuracy_score(y_test, pred),
                "Precision (macro)": precision_score(y_test, pred, average="macro", zero_division=0),
                "Recall (macro)": recall_score(y_test, pred, average="macro", zero_division=0),
                "F1-score (macro)": f1_score(y_test, pred, average="macro", zero_division=0)
            })
        except Exception as exc:
            records.append({"Algorithm": name, "Accuracy": np.nan, "Precision (macro)": np.nan,
                            "Recall (macro)": np.nan, "F1-score (macro)": np.nan,
                            "Error": str(exc)})
    if not fitted:
        raise RuntimeError("None of the models trained successfully. Check the dataset columns and labels.")
    metrics = pd.DataFrame(records).sort_values("F1-score (macro)", ascending=False, na_position="last")
    training_info = {
        "training_rows": len(work_df), "full_rows": len(df), "cache_status": "trained"
    }
    _save_models(cache_key, settings, fitted, metrics, feature_cols, training_info)
    return fitted, metrics, list(feature_cols), training_info


def predict_disease(model, feature_cols, chosen_symptoms, data_mode):
    chosen = set(chosen_symptoms)
    row = {c: (1 if c in chosen else 0) for c in feature_cols}
    prediction = model.predict(pd.DataFrame([row], columns=feature_cols))[0]
    return str(prediction)


def get_model_metrics(df, target_col, feature_cols):
    return load_or_train_models(df, target_col, feature_cols)[1]
